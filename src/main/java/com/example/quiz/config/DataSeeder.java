    private Category createCategory(String name, String desc) {
        Category c = new Category();
        c.setName(name);
        c.setDescription(desc);
        return categoryRepository.save(c);
    }

    private void createQuiz(String title, String desc, Difficulty diff, Category cat, int time, QuestionData... questions) {
        Quiz quiz = new Quiz();
        quiz.setTitle(title);
        quiz.setDescription(desc);
        quiz.setDifficulty(diff);
        quiz.setCategory(cat);
        quiz.setTimeLimitSeconds(time);
        quiz.setStatus(QuizStatus.PUBLISHED);

        int order = 1;
        for (QuestionData qd : questions) {
            Question q = new Question();
            q.setText(qd.text);
            q.setType(QuestionType.SINGLE_CHOICE);
            q.setPoints(1);
            q.setOrderIndex(order++);
            quiz.addQuestion(q);

            int optOrder = 1;

            List<String> allOptions = Arrays.asList(
                    qd.correct, qd.wrong1, qd.wrong2, qd.wrong3
            );

            for (String optText : allOptions) {
                AnswerOption opt = new AnswerOption();
                opt.setText(optText);
                opt.setCorrect(optText.equals(qd.correct));
                opt.setOrderIndex(optOrder++);
                q.addOption(opt);
            }
        }
        quizRepository.save(quiz);
    }

    private QuestionData q(String text, String correct, String wrong1, String wrong2, String wrong3) {
        return new QuestionData(text, correct, wrong1, wrong2, wrong3);
    }

    private record QuestionData(String text, String correct, String wrong1, String wrong2, String wrong3) {}
